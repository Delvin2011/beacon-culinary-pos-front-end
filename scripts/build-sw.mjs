// O3: writes public/sw.js after `next build` (npm run build). The POS service worker, versioned per build: the
// build id (.next/BUILD_ID) and the files the POS routes need (.next/app-build-manifest.json, plus static/media).
// public/sw.js is git-ignored; deploy.ps1 copies public/ into the standalone output.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const ROUTES_FILE = path.join(ROOT, "src", "sw", "routes.mjs")
const TEMPLATE_FILE = path.join(ROOT, "src", "sw", "sw-template.js")

// The worker's source, from its parts. Pure, for the tests.
export async function buildServiceWorker({ buildId, manifestPages, mediaFiles, routesSource, templateSource }) {
  const { posPrecacheFiles } = await import(pathToFileURL(ROUTES_FILE).href)
  const precache = posPrecacheFiles(manifestPages, mediaFiles)
  if (!precache.some((file) => file.includes("/app/pos/page"))) {
    throw new Error("build-sw: the manifest lists no files for /pos/page")
  }
  return [
    "// Generated by scripts/build-sw.mjs at build time. Do not edit.",
    `const SW_VERSION = ${JSON.stringify(buildId)};`,
    `const PRECACHE = ${JSON.stringify(precache, null, 2)};`,
    "",
    routesSource.replace(/^export /gm, ""),
    templateSource,
  ].join("\n")
}

async function main() {
  const nextDir = path.join(ROOT, ".next")
  const buildId = fs.readFileSync(path.join(nextDir, "BUILD_ID"), "utf8").trim()
  const manifestPages = JSON.parse(fs.readFileSync(path.join(nextDir, "app-build-manifest.json"), "utf8")).pages
  const mediaDir = path.join(nextDir, "static", "media")
  const mediaFiles = fs.existsSync(mediaDir) ? fs.readdirSync(mediaDir) : []
  const source = await buildServiceWorker({
    buildId,
    manifestPages,
    mediaFiles,
    routesSource: fs.readFileSync(ROUTES_FILE, "utf8"),
    templateSource: fs.readFileSync(TEMPLATE_FILE, "utf8"),
  })
  fs.mkdirSync(path.join(ROOT, "public"), { recursive: true })
  fs.writeFileSync(path.join(ROOT, "public", "sw.js"), source)
  console.log(`build-sw: public/sw.js for ${buildId}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err)
    process.exit(1)
  })
}
